      SUBROUTINE RUNJMAP
      CHARACTER*256 FNAME1
      REAL RJ1, RJ2, RJINC, CP1, CP2, CPINC
C
      READ(*,*) RJ1, RJ2, RJINC
      READ(*,*) CP1, CP2, CPINC
      READ(*,1000) FNAME1
C
      CALL CLEARPROMPTS
      CALL PUSHREAL(RJ1)
      CALL PUSHREAL(RJ2)
      CALL PUSHREAL(RJINC)
      CALL PUSHREAL(CP1)
      CALL PUSHREAL(CP2)
      CALL PUSHREAL(CPINC)
      CALL PUSHSTR(FNAME1)
C
      CALL PREPSTATE
      CALL JMAP
      CALL WRITEJMAPRESULT('JMAP')
      RETURN
C
 1000 FORMAT(A)
      END


