      SUBROUTINE WRITEINTERESULT(LABEL,NSTA,MODE)
      INCLUDE 'XROTOR.INC'
      CHARACTER*(*) LABEL
      INTEGER NSTA, MODE
      REAL S1(IX), S2(IX), S3(IX), S4(IX), S5(IX), S6(IX)
      REAL CBACK, DX, XMOD, BETMOD, CMOD, XMID, CMID, DCDX, CEXT
      REAL XOCTE
      INTEGER IR
C
      CALL SPLINE(CH,  S1,T,II)
      CALL SPLINE(BETA,S2,T,II)
      CALL SPLINE(CL,  S3,T,II)
      CALL SPLINE(CH,  S4,XI(1),II)
      CALL SPLINE(BETA,S5,XI(1),II)
      CALL SPLINE(CL,  S6,XI(1),II)
C
      WRITE(*,'(A,1X,A)') 'RESULT', LABEL
      CALL WINT(NSTA)
      XOCTE = 0.70
      DO IR=1, NSTA
        IF(MODE.EQ.1) THEN
          CBACK = (0.75-XPITCH)*W1(IR)
          DX = (CBACK*COS(W2(IR)))**2 / W0(IR)
          XMOD = W0(IR) + DX
          XMOD = AMIN1(0.99999,XMOD)
          IF(W0(IR).GE.XI0) THEN
            XT = TINVRT(XMOD)
            BETMOD = SEVAL(XT,BETA,S2,T,II)
          ELSE
            BETMOD = SEVAL(W0(IR),BETA,S5,XI(1),II)
          ENDIF
C
          CMOD = W1(IR)
          IF(IR.GT.1) THEN
            XMID = 0.5*(W0(IR-1) + W0(IR))
            IF(XMID.GE.XI0) THEN
              XT = TINVRT(XMID)
              CMID = SEVAL(XT,CH,S1,T,II)
            ELSE
              CMID = SEVAL(XMID,CH,S4,XI(1),II)
            ENDIF
            DCDX = (W1(IR-1) - W1(IR)) / (W0(IR-1) - W0(IR))
            CEXT = CMID + DCDX*(W0(IR)-XMID)
            CMOD = AMAX1(CMOD,CEXT)
          ENDIF
          IF(IR.LT.NSTA) THEN
            XMID = 0.5*(W0(IR+1) + W0(IR))
            IF(XMID.GE.XI0) THEN
              XT = TINVRT(XMID)
              CMID = SEVAL(XT,CH,S1,T,II)
            ELSE
              CMID = SEVAL(XMID,CH,S4,XI(1),II)
            ENDIF
            DCDX = (W1(IR+1) - W1(IR)) / (W0(IR+1) - W0(IR))
            CEXT = CMID + DCDX*(W0(IR)-XMID)
            CMOD = AMAX1(CMOD,CEXT)
          ENDIF
C
          CALL WREAL(W0(IR))
          CALL WREAL(W1(IR))
          CALL WREAL(W2(IR))
          CALL WREAL(W3(IR))
          CALL WREAL(W4(IR))
          CALL WREAL(W9(IR))
          CALL WREAL(BETMOD)
          CALL WREAL(CMOD)
        ELSE
          CALL WREAL(W0(IR))
          CALL WREAL(W1(IR))
          CALL WREAL(W2(IR))
          CALL WREAL(W3(IR))
          CALL WREAL(W4(IR))
          CALL WREAL(W9(IR))
          CALL WREAL(XOCTE*W1(IR))
        ENDIF
      ENDDO
      RETURN
      END


      SUBROUTINE WRITEJMAPRESULT(LABEL)
      INCLUDE 'XROTOR.INC'
      CHARACTER*(*) LABEL
      INTEGER I
C
      WRITE(*,'(A,1X,A)') 'RESULT', LABEL
      CALL WREAL(ADV)
      CALL WREAL(VEL)
      CALL WINT(II)
      DO I=1, II
        CALL WREAL(BETA(I))
      ENDDO
      RETURN
      END


      SUBROUTINE WREAL(X)
      REAL X
      WRITE(*,'(1X,ES24.16)') X
      RETURN
      END


      SUBROUTINE WINT(I)
      INTEGER I
      WRITE(*,'(1X,I12)') I
      RETURN
      END


      SUBROUTINE CLEARPROMPTS
      INTEGER MAXANS
      PARAMETER (MAXANS=32)
      REAL REALANS(MAXANS)
      LOGICAL LOGANS(MAXANS)
      CHARACTER*256 STRANS(MAXANS)
      INTEGER NREAL, IREAL, NLOG, ILOG, NSTR, ISTR
      COMMON /PROMPTREAL/ REALANS, NREAL, IREAL
      COMMON /PROMPTLOG/  LOGANS,  NLOG,  ILOG
      COMMON /PROMPTSTR/  STRANS,  NSTR,  ISTR
C
      NREAL = 0
      IREAL = 1
      NLOG = 0
      ILOG = 1
      NSTR = 0
      ISTR = 1
      RETURN
      END


      SUBROUTINE PUSHREAL(VALUE)
      INTEGER MAXANS
      PARAMETER (MAXANS=32)
      REAL VALUE
      REAL REALANS(MAXANS)
      INTEGER NREAL, IREAL
      COMMON /PROMPTREAL/ REALANS, NREAL, IREAL
C
      NREAL = NREAL + 1
      REALANS(NREAL) = VALUE
      RETURN
      END


      SUBROUTINE PUSHLOG(VALUE)
      INTEGER MAXANS
      PARAMETER (MAXANS=32)
      LOGICAL VALUE
      LOGICAL LOGANS(MAXANS)
      INTEGER NLOG, ILOG
      COMMON /PROMPTLOG/ LOGANS, NLOG, ILOG
C
      NLOG = NLOG + 1
      LOGANS(NLOG) = VALUE
      RETURN
      END


      SUBROUTINE PUSHSTR(VALUE)
      INTEGER MAXANS
      PARAMETER (MAXANS=32)
      CHARACTER*(*) VALUE
      CHARACTER*256 STRANS(MAXANS)
      INTEGER NSTR, ISTR
      COMMON /PROMPTSTR/ STRANS, NSTR, ISTR
C
      NSTR = NSTR + 1
      STRANS(NSTR) = VALUE
      RETURN
      END


      SUBROUTINE ASKR(PROMPT,RINPUT)
      INTEGER MAXANS
      PARAMETER (MAXANS=32)
      CHARACTER*(*) PROMPT
      REAL RINPUT
      REAL REALANS(MAXANS)
      INTEGER NREAL, IREAL
      COMMON /PROMPTREAL/ REALANS, NREAL, IREAL
C
      IF(IREAL.GT.NREAL) STOP 'ASKR underflow'
      RINPUT = REALANS(IREAL)
      IREAL = IREAL + 1
      RETURN
      END


